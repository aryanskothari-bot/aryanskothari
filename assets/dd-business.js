/* Diligence Desk business layer: CIM PDF -> claims, shareable scorecard, deal pipeline with post-closing KPI monitoring */
(function () {
  const { ask, esc, store, toast, download } = App;
  const $ = (id) => document.getElementById(id);

  /* ---------- 1. Upload a CIM / teaser PDF: read in the browser, extract checkable claims ---------- */
  let pdfjs = null;
  async function loadPdf() {
    if (pdfjs) return pdfjs;
    pdfjs = await import("https://cdn.jsdelivr.net/npm/pdfjs-dist@4.7.76/build/pdf.min.mjs");
    pdfjs.GlobalWorkerOptions.workerSrc = "https://cdn.jsdelivr.net/npm/pdfjs-dist@4.7.76/build/pdf.worker.min.mjs";
    return pdfjs;
  }
  async function pdfText(file) {
    const lib = await loadPdf();
    const doc = await lib.getDocument({ data: await file.arrayBuffer() }).promise;
    let out = "";
    for (let i = 1; i <= Math.min(doc.numPages, 25) && out.length < 12000; i++) {
      const pg = await doc.getPage(i), tc = await pg.getTextContent();
      out += tc.items.map((x) => x.str).join(" ") + "\n";
    }
    return { text: out.replace(/\s+/g, " ").slice(0, 12000), pages: doc.numPages };
  }
  $("clPdf").onchange = async (e) => {
    const f = e.target.files[0]; e.target.value = "";
    if (!f) return;
    if (f.size > 25e6) { toast("PDF is over 25 MB"); return; }
    const note = $("clNote"), was = note.textContent;
    note.textContent = "Reading " + f.name + "…";
    try {
      const { text, pages } = await pdfText(f);
      if (text.length < 200) throw new Error("No readable text in this PDF (it may be scanned images).");
      note.textContent = `Read ${pages} pages. Extracting the claims a buyer should verify…`;
      const r = await ask(`You are a buy-side analyst reading a seller's teaser or confidential information memorandum (CIM). From the text below, extract the company name and the 6-8 most decision-relevant FACTUAL claims a buyer must verify (market position, growth, profitability, customer concentration, contracts, team, legal status). Quote figures exactly as written. Skip opinions with nothing to verify.
Return ONLY JSON: {"company":"","claims":["claim, max 20 words"]}
TEXT:
${text}`, "");
      const cl = (r.data.claims || []).filter(Boolean).slice(0, 8);
      if (!cl.length) throw new Error("No checkable claims found in this document.");
      if (r.data.company) $("cCo").value = r.data.company;
      $("clTxt").value = cl.join("\n");
      note.textContent = `${cl.length} claims extracted from ${f.name}. Edit them if you like, then check.`;
      toast("Claims extracted");
    } catch (err) { note.textContent = was; toast(err.message || "Could not read that PDF"); }
  };

  /* ---------- 2. Scorecard: a printable one-pager a seller or buyer can share ---------- */
  $("clScore").onclick = () => {
    const cl = window.__claims || [], co = window.__claimCo || $("cCo").value.trim();
    if (!cl.length) return;
    const n = (v) => cl.filter((c) => c.verdict === v).length, pct = Math.round(((n("Supported") + 0.5 * n("Partly supported")) / cl.length) * 100);
    const col = { Supported: "#14946a", "Partly supported": "#b7791f", Contradicted: "#c2412a", Unverifiable: "#6b6890" };
    const today = new Date().toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });
    const html = `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>Claim Check scorecard: ${esc(co)}</title><style>body{font:14px/1.5 Inter,Arial,sans-serif;color:#1b1846;max-width:760px;margin:32px auto;padding:0 24px}h1{font:400 30px Georgia,serif;margin:4px 0}.k{font:11px monospace;letter-spacing:.1em;text-transform:uppercase;color:#77749a}.score{display:flex;gap:18px;align-items:center;margin:18px 0;padding:16px 18px;border-radius:14px;background:#f3f2fa}.big{font:400 46px Georgia,serif}.row{display:grid;grid-template-columns:130px 1fr;gap:12px;padding:12px 0;border-top:1px solid #e0def0}.v{font-weight:700;font-size:12px}.q{color:#5b4cf0}.foot{margin-top:24px;font-size:11.5px;color:#77749a}@media print{body{margin:0}}</style></head><body><div class="k">Diligence Desk · Claim Check scorecard</div><h1>${esc(co)}</h1><div class="k">Checked ${today} against public sources</div><div class="score"><div class="big">${pct}%</div><div><b>of claims supported by public evidence</b><br>${n("Supported")} supported · ${n("Partly supported")} partly · ${n("Contradicted")} contradicted · ${n("Unverifiable")} unverifiable<br>${esc(window.__claimOverall || "")}</div></div>${cl.map((c) => `<div class="row"><div class="v" style="color:${col[c.verdict] || "#6b6890"}">${esc(c.verdict)}</div><div><b>${esc(c.claim)}</b><br>${esc(c.evidence)}<br><span class="q">To verify: ${esc(c.ask)}</span></div></div>`).join("")}<p class="foot">Generated by Diligence Desk (aryanskothari.vercel.app). An automated first screen from public sources, not an audit, valuation or investment advice. "Unverifiable" means no public evidence either way; confirm in the data room. See aryanskothari.vercel.app/legal.html.</p><script>setTimeout(()=>print(),400)<\/script></body></html>`;
    const w = window.open("", "_blank");
    if (w) { w.document.write(html); w.document.close(); }
    else download(`claim-check-${co.replace(/\W+/g, "-").toLowerCase()}.html`, html, "text/html");
  };

  /* ---------- 3. Deal pipeline + post-closing monitoring (saved on this device) ---------- */
  const STAGES = ["Screening", "LOI sent", "Confirmatory diligence", "Signed", "Closed: monitoring", "Passed"];
  const KS = ["On track", "Watch", "Breached"];
  let deals = store.get("dd_deals", []);
  const save = () => { store.set("dd_deals", deals); render(); };

  window.addEventListener("dd:company-done", (e) => {
    const S = e.detail; if (!S || !S.co) return;
    const pm = (S.ic && S.ic.premortem) || {};
    const prev = deals.find((d) => d.co.toLowerCase() === S.co.toLowerCase());
    const d = {
      id: prev ? prev.id : Date.now().toString(36), co: S.co, buyer: S.buyer || "", date: new Date().toISOString().slice(0, 10),
      verdict: (S.ic && S.ic.verdict) || "No verdict", score: S.ic ? Math.round(+S.ic.score || 0) : null,
      stage: prev ? prev.stage : "Screening",
      flags: ((S.ic && S.ic.top_flags) || []).slice(0, 3),
      walk: pm.walk_away_if || [],
      kpis: (pm.early_warnings || []).map((w, i) => ({ kpi: w.kpi, threshold: w.threshold, status: (prev && prev.kpis && prev.kpis[i] && prev.kpis[i].status) || "On track" })),
      claims: (S.claims || []).map((c) => c.verdict),
    };
    deals = [d, ...deals.filter((x) => x.id !== d.id)].slice(0, 40);
    save(); toast("Saved to your deal pipeline");
  });

  window.addEventListener("dd:claims", (e) => {
    const d = deals.find((x) => x.co.toLowerCase() === String(e.detail.co).toLowerCase());
    if (d) { d.claims = e.detail.claims.map((c) => c.verdict); save(); }
  });
  function render() {
    const el = $("pipeList");
    if (!deals.length) { el.innerHTML = '<p style="color:var(--ink-2);margin:6px 0 0">Every company you run through due diligence is saved here with its verdict, red flags and the early-warning KPIs from the pre-mortem. After closing, mark each KPI each month: breaches show at the top.</p>'; return; }
    const sorted = [...deals].sort((a, b) => b.kpis.filter((k) => k.status === "Breached").length - a.kpis.filter((k) => k.status === "Breached").length);
    el.innerHTML = sorted.map((d) => {
      const br = d.kpis.filter((k) => k.status === "Breached").length, wa = d.kpis.filter((k) => k.status === "Watch").length;
      const vt = /do not/i.test(d.verdict) ? "red" : /condition/i.test(d.verdict) ? "amber" : /proceed/i.test(d.verdict) ? "green" : "";
      const cc = d.claims.length ? `${d.claims.filter((v) => v === "Supported").length}/${d.claims.length} claims supported` : "";
      return `<div class="deal" data-id="${esc(d.id)}"><div class="top2"><b>${esc(d.co)}</b>${d.buyer ? `<span class="tag">buyer: ${esc(d.buyer)}</span>` : ""}<span class="tag ${vt}">${esc(d.verdict)}${d.score != null ? " · " + d.score + "/100" : ""}</span>${cc ? `<span class="tag">${cc}</span>` : ""}${br ? `<span class="tag red">${br} KPI breached</span>` : wa ? `<span class="tag amber">${wa} to watch</span>` : ""}<span class="sp" style="flex:1"></span><label class="sr" for="st-${esc(d.id)}">Stage</label><select id="st-${esc(d.id)}" data-stage>${STAGES.map((s) => `<option${s === d.stage ? " selected" : ""}>${s}</option>`).join("")}</select><button class="btn sm" data-rerun>Re-run</button><button class="btn sm" data-del aria-label="Remove ${esc(d.co)}">✕</button></div>
        <div style="font-size:12.5px;color:var(--ink-3);margin-top:4px">Last run ${esc(d.date)}${d.flags.length ? " · top flag: " + esc(d.flags[0]) : ""}</div>
        ${d.kpis.length ? `<details${br || d.stage.startsWith("Closed") ? " open" : ""}><summary>Post-closing monitoring (${d.kpis.length} KPIs from the pre-mortem)</summary>${d.kpis.map((k, i) => `<div class="kpirow"><span>${esc(k.kpi)}</span><span style="color:var(--ink-3)">act if ${esc(k.threshold)}</span><select data-kpi="${i}" aria-label="Status of ${esc(k.kpi)}">${KS.map((s) => `<option${s === k.status ? " selected" : ""}>${s}</option>`).join("")}</select></div>`).join("")}${d.walk.length ? `<div class="k" style="margin-top:10px">Walk away if</div><ul style="margin:0;padding-left:18px">${d.walk.map((w) => `<li>${esc(w)}</li>`).join("")}</ul>` : ""}</details>` : ""}</div>`;
    }).join("");
  }
  $("pipeList").addEventListener("change", (e) => {
    const card = e.target.closest("[data-id]"); if (!card) return;
    const d = deals.find((x) => x.id === card.dataset.id); if (!d) return;
    if (e.target.matches("[data-stage]")) d.stage = e.target.value;
    if (e.target.matches("[data-kpi]")) { d.kpis[+e.target.dataset.kpi].status = e.target.value; if (e.target.value === "Breached") toast(`${d.co}: early warning breached. Check the walk-away list.`); }
    save();
  });
  $("pipeList").addEventListener("click", (e) => {
    const card = e.target.closest("[data-id]"); if (!card) return;
    const d = deals.find((x) => x.id === card.dataset.id); if (!d) return;
    if (e.target.matches("[data-del]")) { deals = deals.filter((x) => x !== d); save(); }
    if (e.target.matches("[data-rerun]")) DD.goCompany(d.co, d.buyer);
  });
  $("pipeCsv").onclick = () => {
    if (!deals.length) { toast("No deals yet"); return; }
    const rows = [["Company", "Buyer", "Stage", "Verdict", "Score", "Last run", "KPIs breached", "Top flag"], ...deals.map((d) => [d.co, d.buyer, d.stage, d.verdict, d.score ?? "", d.date, d.kpis.filter((k) => k.status === "Breached").length, d.flags[0] || ""])];
    download("deal-pipeline.csv", rows.map((r) => r.map((v) => `"${String(v).replace(/"/g, '""')}"`).join(",")).join("\n"), "text/csv");
  };
  render();
})();
